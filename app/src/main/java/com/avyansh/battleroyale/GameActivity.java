package com.avyansh.battleroyale;

import android.app.Activity;
import android.content.Intent;
import android.content.SharedPreferences;
import android.graphics.Typeface;
import android.os.Build;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.view.Gravity;
import android.view.View;
import android.view.Window;
import android.view.WindowInsets;
import android.view.WindowInsetsController;
import android.view.WindowManager;
import android.widget.FrameLayout;
import android.widget.LinearLayout;
import android.widget.TextView;

import java.util.ArrayList;

/**
* The match screen. The lobby starts it with a brand new GAME ID every time START is pressed:
*   EXTRA_GAME_ID    id of this match (online: generated by the host and shared with the whole room)
*   EXTRA_ONLINE     true = real players in a room, false = offline vs bots
*   EXTRA_ROOM       room code (online only)
*   EXTRA_TEAM       my team number (online only)
*   EXTRA_TEAM_SIZE  1 solo / 2 duo / 4 squad
* Closing this activity returns to the lobby (the room stays open, the host can start the next game).
*/
public class GameActivity extends Activity implements Net.Listener {
	
	public static final String EXTRA_GAME_ID = "game_id";
	public static final String EXTRA_ONLINE = "online";
	public static final String EXTRA_ROOM = "room";
	public static final String EXTRA_TEAM = "team";
	public static final String EXTRA_TEAM_SIZE = "team_size";
	
	private Game3DView gameView;
	private HudController hud;
	private GameEngine eng;
	private View loading, exitBtn;
	private LinearLayout squadPanel;
	private TextView gameIdChip, zoneChip, zoneWarning;
	private View zoneVignette;
	private FrameLayout nameTagLayer;
	private final ArrayList<TextView> tagPool = new ArrayList<>();
	
	private String gameId = "";
	private boolean online;
	private boolean closing;
	private boolean serverMode, resultsQueued;
	private boolean loadingHidden;
	private int lastSquadKey = -1;
	private final Handler ui = new Handler(Looper.getMainLooper());
	
	private static final int TAG_INTERVAL_MS = 50;
	private static final int MAX_TAG_VIEWS = 10;
	
	private final Runnable tagTick = new Runnable() {
		@Override public void run() {
			if (closing) return;
			updateNameTags();
			ui.postDelayed(this, TAG_INTERVAL_MS);
		}
	};
	
	private final Runnable tick = new Runnable() {
		@Override public void run() {
			if (closing) return;
			updateOverlay();
			if (serverMode && ServerNet.matchFinished() && !resultsQueued) {
				resultsQueued = true;   // server sent match_end: show the results after a short pause
				ui.postDelayed(new Runnable() { @Override public void run() { exitToLobby(); } }, 3500);
			}
			ui.postDelayed(this, 300);
		}
	};
	
	@Override protected void onCreate(Bundle b) {
		super.onCreate(b);
		goFullscreen();
		getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
		setContentView(R.layout.game);
		Net.init(this);
		
		Intent in = getIntent();
		gameId = in.getStringExtra(EXTRA_GAME_ID);
		if (gameId == null || gameId.length() == 0) gameId = Net.newGameId();
		// the process may have been recreated: online only makes sense while the room/match still exists
		online = in.getBooleanExtra(EXTRA_ONLINE, false) && Net.active && Net.inMatch;
		serverMode = online && ServerNet.inServerMatch();
		if (!online) Net.inMatch = false;
		Net.listener = this;
		
		SharedPreferences saved = getSharedPreferences("avyansh_game_settings", MODE_PRIVATE);
		applyGraphicsPreset(saved.getInt("quality", 1));
		
		FrameLayout container = findViewById(R.id.game_container);
		gameView = new Game3DView(this);
		gameView.setSensitivity(saved.getFloat("sensitivity", 1.0f));
		gameView.setGyroAimEnabled(saved.getBoolean("gyro", false));
		gameView.getEngine().applyPrefs(saved);
		VoiceChat.muted = saved.getBoolean("voice_muted", false);
		container.addView(gameView, new FrameLayout.LayoutParams(
		FrameLayout.LayoutParams.MATCH_PARENT, FrameLayout.LayoutParams.MATCH_PARENT));
		eng = gameView.getEngine();
		
		hud = new HudController(this, findViewById(R.id.hud_root), gameView);
		hud.allowRespawn = !online;
		hud.show(true);
		
		zoneChip = findViewById(R.id.zone_chip);
		zoneWarning = findViewById(R.id.zone_warning);
		zoneVignette = findViewById(R.id.zone_vignette);
		nameTagLayer = findViewById(R.id.name_tags);
		loading = findViewById(R.id.loading_overlay);
		exitBtn = findViewById(R.id.btn_exit_lobby);
		squadPanel = findViewById(R.id.squad_panel);
		gameIdChip = findViewById(R.id.game_id_chip);
		gameIdChip.setText("GAME ID  " + gameId);
		((TextView) findViewById(R.id.loading_game_id)).setText("GAME ID  " + gameId);
		((TextView) findViewById(R.id.loading_sub)).setText(online
		? "Room " + Net.room + "  \u2022  " + teamName(in.getIntExtra(EXTRA_TEAM_SIZE, Net.teamSize))
		: "Offline battle  \u2022  you vs " + BotManager.DEFAULT_BOT_COUNT + " named bots");
		exitBtn.setOnClickListener(v -> exitToLobby());
		
		// ─────────────────────────────────────────────────────────────
		// A match has 50 participants: bots fill seats not taken by
		// real players. Online: real players in room, Offline: just us.
		// ─────────────────────────────────────────────────────────────
		// Server matches: the dedicated server owns the bots (flagged isBot), so no local bots are ever spawned.
		int realPlayers = serverMode ? ServerNet.serverRealPlayers() : ((online && Net.active) ? (1 + Net.otherCount()) : 1);
		int botsToSpawn = serverMode ? ServerNet.serverBots() : Math.max(0, BotManager.MATCH_SIZE - realPlayers);
		eng.bots.botCount = serverMode ? 0 : botsToSpawn;
		eng.setMatchInfo(realPlayers, botsToSpawn);
		
		android.util.Log.i("GameActivity",
		"Match starting: " + realPlayers + " real players, " + botsToSpawn + " bots (total "
		+ (realPlayers + botsToSpawn) + ")");
		
		// GAME ID is the seed: zone circles, bot names and bot spawns
		// are identical for every device in the room.
		eng.matchSeed = serverMode ? 0L : (online ? gameId.hashCode() : 0L);
		if (serverMode) addVoiceButton(container);
		
		final GameEngine e = eng;
		gameView.queueEvent(new Runnable() {
			@Override public void run() {
				e.startMatch();
			}
		});
	}
	

	/** Push-to-talk button for squad voice chat (needs RECORD_AUDIO; voice goes only to living squad mates). */
	private void addVoiceButton(FrameLayout container) {
		if (ServerNet.squad == null || ServerNet.myTeamSize() <= 1) return;
		final TextView mic = Ui.button(this, "MIC", Ui.SECONDARY, null);
		mic.setOnTouchListener(new View.OnTouchListener() {
			@Override public boolean onTouch(View v, android.view.MotionEvent e) {
				int a = e.getActionMasked();
				if (a == android.view.MotionEvent.ACTION_DOWN) {
					if (checkSelfPermission(android.Manifest.permission.RECORD_AUDIO) != android.content.pm.PackageManager.PERMISSION_GRANTED) {
						requestPermissions(new String[] { android.Manifest.permission.RECORD_AUDIO }, 77);
						return true;
					}
					VoiceChat.setTalking(true);
					mic.setText("TALK");
				} else if (a == android.view.MotionEvent.ACTION_UP || a == android.view.MotionEvent.ACTION_CANCEL) {
					VoiceChat.setTalking(false);
					mic.setText("MIC");
				}
				return true;
			}
		});
		FrameLayout.LayoutParams lp = new FrameLayout.LayoutParams(dp(64), dp(40));
		lp.gravity = android.view.Gravity.START | android.view.Gravity.TOP;
		lp.leftMargin = dp(150); lp.topMargin = dp(60);
		container.addView(mic, lp);
	}

	private static String teamName(int size) {
		return size <= 1 ? "SOLO" : (size == 2 ? "DUO" : "SQUAD");
	}
	
	// ------------------------------------------------------------------ overlay (game id, squad, exit button, loading cover)
	private void updateOverlay() {
		if (eng == null) return;
		MatchPhase ph = eng.match.phase;
		
		if (!loadingHidden && !eng.lobby && ph != MatchPhase.LOBBY) {
			loadingHidden = true;
			loading.animate().alpha(0f).setDuration(350).withEndAction(new Runnable() {
				@Override public void run() { loading.setVisibility(View.GONE); }
			}).start();
		}
		
		boolean over = ph == MatchPhase.DEAD || ph == MatchPhase.WIN;
		// offline keeps the HUD's RESPAWN / PLAY AGAIN button; the lobby button is always offered once the match is over
		exitBtn.setVisibility(over ? View.VISIBLE : View.GONE);
		
		if (online) refreshSquad();
		updateZoneHud();
	}
	
	/** Zone timer chip, outside-zone warning and blue screen tint. */
	private void updateZoneHud() {
		ZoneController z = eng.zone;
		boolean show = z.isActive() && eng.match.phase != MatchPhase.LOBBY;
		zoneChip.setVisibility(show ? View.VISIBLE : View.GONE);
		if (!show) { zoneWarning.setVisibility(View.GONE); zoneVignette.setAlpha(0f); return; }
		zoneChip.setText(z.statusLine());
		zoneChip.setTextColor(z.isShrinking() ? 0xFFFFB35A : 0xFF8FD0FF);
		boolean outside = z.isPlayerOutside() && eng.match.phase == MatchPhase.PLAYING;
		zoneWarning.setVisibility(outside ? View.VISIBLE : View.GONE);
		if (outside) {
			int dist = Math.round(z.distanceOutside(eng.player.x, eng.player.z));
			zoneWarning.setText("OUTSIDE SAFE ZONE  \u2022  " + dist + " m  \u2022  -" + String.format(java.util.Locale.US, "%.1f", z.damagePerSecond()) + " HP/s");
		}
		zoneVignette.animate().alpha(outside ? 0.85f : 0f).setDuration(250).start();
	}
	
	/** Positions the name tags the renderer computed (teammates, nearby enemies, closest bots). */
	private void updateNameTags() {
		if (eng == null || nameTagLayer.getWidth() == 0) return;
		NameTag[] tags = eng.nameTags;
		int used = Math.min(tags.length, MAX_TAG_VIEWS);
		while (tagPool.size() < used) {
			TextView t = new TextView(this);
			t.setTextSize(10);
			t.setTypeface(Typeface.DEFAULT, Typeface.BOLD);
			t.setSingleLine(true);
			t.setPadding(dp(6), dp(1), dp(6), dp(1));
			t.setBackgroundResource(R.drawable.bg_hud_chip);
			nameTagLayer.addView(t, new FrameLayout.LayoutParams(-2, -2));
			tagPool.add(t);
		}
		for (int i = 0; i < tagPool.size(); i++) {
			TextView t = tagPool.get(i);
			if (i >= used) { t.setVisibility(View.GONE); continue; }
			NameTag tag = tags[i];
			if (!tag.name.contentEquals(t.getText())) t.setText(tag.name);
			t.setTextColor(tag.friend ? 0xFF7DFF9A : (tag.bot ? 0xFFE8EEF2 : 0xFFFF8A8A));
			t.measure(0, 0);
			t.setTranslationX(tag.x * nameTagLayer.getWidth() - t.getMeasuredWidth() / 2f);
			t.setTranslationY(tag.y * nameTagLayer.getHeight() - t.getMeasuredHeight());
			t.setVisibility(View.VISIBLE);
		}
	}
	
	private void refreshSquad() {
		ArrayList<NetPlayer> mates = Net.teammates();
		int key = mates.size() * 1000;
		for (int i = 0; i < mates.size(); i++) {
			NetPlayer m = mates.get(i);
			key += (m.alive ? 1 : 0) * 7 + Math.max(0, m.hp) / 10 + m.name.hashCode() % 13;
		}
		if (key == lastSquadKey) return;
		lastSquadKey = key;
		squadPanel.removeAllViews();
		for (int i = 0; i < mates.size(); i++) {
			NetPlayer m = mates.get(i);
			TextView t = new TextView(this);
			t.setText(m.name + (m.alive ? "  " + Math.max(0, m.hp) + " HP" : "  \u2715 DOWN"));
			t.setTextColor(m.alive ? 0xFF7DFF9A : 0xFFFF7777);
			t.setTextSize(10);
			t.setTypeface(Typeface.DEFAULT, Typeface.BOLD);
			t.setBackgroundResource(R.drawable.bg_hud_chip);
			t.setPadding(dp(8), dp(3), dp(8), dp(3));
			t.setSingleLine(true);
			LinearLayout.LayoutParams lp = new LinearLayout.LayoutParams(-2, -2);
			lp.bottomMargin = dp(3);
			squadPanel.addView(t, lp);
		}
	}
	
	// ------------------------------------------------------------------ leaving
	private void exitToLobby() {
		if (closing) return;
		closing = true;
		ui.removeCallbacks(tick);
		if (serverMode) {
			if (ServerNet.matchFinished()) startActivity(new android.content.Intent(this, MatchResultsActivity.class));
			else { ServerNet.endMatchLocal(); }
			VoiceChat.release();
		} else Net.endMatch();   // online: tell the room we are out; the host re-opens it for the next game
		finish();
	}
	
	@Override public void onBackPressed() {
		MatchPhase ph = eng == null ? MatchPhase.LOBBY : eng.match.phase;
		if (ph == MatchPhase.DEAD || ph == MatchPhase.WIN) { exitToLobby(); return; }
		PremiumDialog.show(this, "LEAVE MATCH?", "GAME ID  " + gameId,
		PremiumDialog.text(this, online
		? "You will leave this match and go back to the lobby. Your team keeps playing."
		: "Your current battle progress will be lost.", 13, 0xFFEAF1F7, false),
		"LEAVE", new Runnable() { @Override public void run() { exitToLobby(); } },
		"STAY", null, GameDialog.Tone.DANGER);
	}
	
	// ------------------------------------------------------------------ lifecycle
	@Override protected void onResume() {
		super.onResume();
		if (gameView != null) gameView.onResume();
		goFullscreen();
		ui.removeCallbacks(tick);
		ui.post(tick);
		ui.removeCallbacks(tagTick);
		ui.post(tagTick);
	}
	
	@Override protected void onPause() {
		super.onPause();
		if (gameView != null) gameView.onPause();
		ui.removeCallbacks(tick);
		ui.removeCallbacks(tagTick);
	}
	
	@Override protected void onDestroy() {
		super.onDestroy();
		closing = true;
		ui.removeCallbacks(tick);
		if (hud != null) hud.stop();
		if (gameView != null) {
			gameView.setJoystickListener(null);
			gameView.setLookTapListener(null);
		}
		if (Net.listener == this) Net.listener = null;
		// closed by the system / swiped away while a match was running: make sure the room is not left hanging
		if (serverMode) { if (!ServerNet.matchFinished()) ServerNet.endMatchLocal(); VoiceChat.release(); }
		else if (Net.inMatch) Net.endMatch();
	}
	
	// Net.Listener: the lobby handles room changes, nothing to do while playing
	@Override public void onRoomChanged() { }
	@Override public void onStatus(String msg) { }
	@Override public void onMatchStart() { }
	
	// ------------------------------------------------------------------ helpers
	private int dp(int v) { return Math.round(getResources().getDisplayMetrics().density * v); }
	
	private void applyGraphicsPreset(int q) {
		if (q == 0) {
			GameSettings.VIEW_RADIUS_CHUNKS = 3;
			GameSettings.MAX_TREE_TRIS = 18000;
			GameSettings.MAX_BUILDING_TRIS = 18000;
			GameSettings.TREE_HI_DIST = 75f;
		} else if (q == 2) {
			GameSettings.VIEW_RADIUS_CHUNKS = 5;
			GameSettings.MAX_TREE_TRIS = 50000;
			GameSettings.MAX_BUILDING_TRIS = 50000;
			GameSettings.TREE_HI_DIST = 140f;
		} else {
			GameSettings.VIEW_RADIUS_CHUNKS = 4;
			GameSettings.MAX_TREE_TRIS = 35000;
			GameSettings.MAX_BUILDING_TRIS = 35000;
			GameSettings.TREE_HI_DIST = 110f;
		}
	}
	
	private void goFullscreen() {
		try {
			Window window = getWindow();
			window.setFlags(WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS, WindowManager.LayoutParams.FLAG_LAYOUT_NO_LIMITS);
			if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
				window.setDecorFitsSystemWindows(false);
				WindowInsetsController c = window.getInsetsController();
				if (c != null) {
					c.hide(WindowInsets.Type.statusBars() | WindowInsets.Type.navigationBars());
					c.setSystemBarsBehavior(WindowInsetsController.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
				}
			} else {
				window.setFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN, WindowManager.LayoutParams.FLAG_FULLSCREEN);
				window.getDecorView().setSystemUiVisibility(
				View.SYSTEM_UI_FLAG_LAYOUT_STABLE | View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN
				| View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION | View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY
				| View.SYSTEM_UI_FLAG_FULLSCREEN | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION);
			}
			if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
				WindowManager.LayoutParams lp = window.getAttributes();
				lp.layoutInDisplayCutoutMode = WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_SHORT_EDGES;
				window.setAttributes(lp);
			}
		} catch (RuntimeException ignored) { }
	}
}
